"""Provenance primitives: every data point carries `source`, `as_of` and `stale`."""

from __future__ import annotations

from datetime import UTC, datetime, timedelta
from enum import StrEnum
from typing import Annotated, Generic, TypeVar

from pydantic import AfterValidator, BaseModel, ConfigDict, Field


def _require_aware(dt: datetime) -> datetime:
    if dt.tzinfo is None or dt.utcoffset() is None:
        raise ValueError(f"naive datetime not allowed (got {dt!r}); attach a timezone")
    return dt.astimezone(UTC)


AwareDatetime = Annotated[datetime, AfterValidator(_require_aware)]
"""A timezone-aware datetime, normalised to UTC. Naive datetimes fail validation."""


class Source(StrEnum):
    SYNTHETIC = "synthetic"  # generated by mp_core.synthetic; never evaluate on this
    RECORDED = "recorded"  # our own recordings of a live feed, replayed
    NSE_BHAVCOPY = "nse_bhavcopy"
    KITE = "kite"
    UPSTOX = "upstox"
    FYERS = "fyers"
    DERIVED = "derived"  # computed by mp_core from other sourced inputs
    NEWS_FEED = "news_feed"  # a real RSS/Atom/announcements feed (the feed name is kept per item)


class StrictModel(BaseModel):
    """Base for external data: unknown fields and type coercion surprises fail loudly."""

    model_config = ConfigDict(extra="forbid", frozen=True, str_strip_whitespace=True)


T = TypeVar("T")


class Sourced(BaseModel, Generic[T]):
    """Envelope that makes provenance impossible to drop."""

    model_config = ConfigDict(frozen=True)

    value: T
    source: Source
    as_of: AwareDatetime
    ttl_seconds: float = Field(gt=0)
    stale: bool

    @property
    def is_synthetic(self) -> bool:
        return self.source is Source.SYNTHETIC

    def restamp(self, now: datetime) -> Sourced[T]:
        """Re-evaluate staleness against a new `now` (e.g. when served from cache)."""
        return self.model_copy(update={"stale": is_stale(self.as_of, now, self.ttl_seconds)})


def is_stale(as_of: datetime, now: datetime, ttl_seconds: float) -> bool:
    _require_aware(now)
    return (now - as_of) > timedelta(seconds=ttl_seconds)


def stamp(value: T, *, source: Source, as_of: datetime, now: datetime, ttl_seconds: float) -> Sourced[T]:
    """Wrap a value with provenance; staleness is computed, never passed in by hand."""
    return Sourced[type(value)](  # type: ignore[misc]
        value=value,
        source=source,
        as_of=as_of,
        ttl_seconds=ttl_seconds,
        stale=is_stale(_require_aware(as_of), now, ttl_seconds),
    )


def derived_source(sources: list[Source]) -> Source:
    """Provenance of a value computed from several inputs. Synthetic is contagious: anything
    computed from a synthetic input is synthetic. A single shared source is kept as-is."""
    if not sources:
        raise ValueError("derived value needs at least one input")
    if Source.SYNTHETIC in sources:
        return Source.SYNTHETIC
    return sources[0] if len(set(sources)) == 1 else Source.DERIVED


def derive(value: T, inputs: list[Sourced], *, now: datetime) -> Sourced[T]:
    """Wrap a computed value: as_of = oldest input; stale as soon as *any* input expires.

    The TTL is chosen so that later `restamp()` calls reproduce exactly that rule:
    expires_at = min(as_of_i + ttl_i), ttl = expires_at - as_of. (Pairing the oldest as_of with
    the tightest TTL would mark a fresh 5 s quote + a 40 s old 1-minute bar as stale forever.)"""
    inputs = [i for i in inputs if i is not None]
    if not inputs:
        raise ValueError("derive() needs at least one sourced input")
    as_of = min(i.as_of for i in inputs)
    expires_at = min(i.as_of + timedelta(seconds=i.ttl_seconds) for i in inputs)
    ttl = max((expires_at - as_of).total_seconds(), 1e-6)
    stale = any(is_stale(i.as_of, now, i.ttl_seconds) for i in inputs)
    return Sourced[type(value)](  # type: ignore[misc]
        value=value, source=derived_source([i.source for i in inputs]), as_of=as_of, ttl_seconds=ttl, stale=stale
    )
